import { SlashCommandBuilder } from 'discord.js';
import type { BotCommand } from '../types/command.js';
import { generateJoke } from '../services/jokeEngine.js';

export const roastCommand: BotCommand = {
  data: new SlashCommandBuilder()
    .setName('roast')
    .setDescription('Give one member a chaotic but friendly roast.')
    .addUserOption((option) => option.setName('member').setDescription('Who is getting roasted?').setRequired(true)),
  async execute(interaction) {
    const member = interaction.options.getUser('member', true);
    await interaction.deferReply();
    const result = await generateJoke('roast', [(member.globalName ?? member.username)]);
    await interaction.editReply({
      content: `🎯 ${member} ${result.joke}\n\n-# Generated by Bait Bot · ${result.source}`,
      allowedMentions: { users: [], roles: [], repliedUser: false },
    });
  },
};
