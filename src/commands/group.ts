import { SlashCommandBuilder } from 'discord.js';
import type { BotCommand } from '../types/command.js';
import { generateJoke } from '../services/jokeEngine.js';

export const groupCommand: BotCommand = {
  data: new SlashCommandBuilder()
    .setName('group')
    .setDescription('Generate a chaotic group roast for 3–5 members.')
    .addUserOption((option) => option.setName('member1').setDescription('First member').setRequired(true))
    .addUserOption((option) => option.setName('member2').setDescription('Second member').setRequired(true))
    .addUserOption((option) => option.setName('member3').setDescription('Third member').setRequired(true))
    .addUserOption((option) => option.setName('member4').setDescription('Optional fourth member').setRequired(false))
    .addUserOption((option) => option.setName('member5').setDescription('Optional fifth member').setRequired(false)),
  async execute(interaction) {
    const members = ['member1', 'member2', 'member3', 'member4', 'member5']
      .map((key) => interaction.options.getUser(key))
      .filter((member): member is NonNullable<typeof member> => member !== null);

    const uniqueMembers = [...new Map(members.map((member) => [member.id, member])).values()];
    if (uniqueMembers.length < 3) {
      await interaction.reply({ content: 'Pick at least three different members for maximum chaos.', ephemeral: true });
      return;
    }

    await interaction.deferReply();
    const result = await generateJoke('group', uniqueMembers.map((member) => (member.globalName ?? member.username)));
    const mentions = uniqueMembers.map((member) => member.toString()).join(' ');
    await interaction.editReply({
      content: `💀 **THE CHAOS SQUAD**\n${mentions}\n${result.joke}\n\n-# Generated by Bait Bot · ${result.source}`,
      allowedMentions: { users: [], roles: [], repliedUser: false },
    });
  },
};
